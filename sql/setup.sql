CREATE TABLE IF NOT EXISTS TUNE_BI_DB.APP_STATE.DATA_REQUEST_TICKET (
  TICKET_ID VARCHAR(50) NOT NULL,
  BUSINESS_UNIT VARCHAR(100) NOT NULL,
  REQUESTER VARCHAR(100) NOT NULL,
  TITLE VARCHAR(200) NOT NULL,
  DESCRIPTION VARCHAR(4000) NOT NULL,
  BUSINESS_JUSTIFICATION VARCHAR(2000) NOT NULL,
  CATEGORY VARCHAR(30) NOT NULL,
  PRIORITY VARCHAR(10) NOT NULL,
  ASSIGNED_TO VARCHAR(100),
  STATUS VARCHAR(20) NOT NULL DEFAULT 'NEW',
  CREATED_AT TIMESTAMP_LTZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
  UPDATED_AT TIMESTAMP_LTZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
  PROGRESS_NOTES VARCHAR(4000),
  RESOLUTION_NOTES VARCHAR(4000),
  VERSION NUMBER NOT NULL DEFAULT 1
